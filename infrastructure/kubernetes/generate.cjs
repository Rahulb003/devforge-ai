// ---------------------------------------------------------------- YAML helpers

const q = (s) => JSON.stringify(String(s)); // JSON strings are valid YAML scalars
const indent = (text, n) => text.split("\n").map((l) => (l ? " ".repeat(n) + l : l)).join("\n");
const literal = (text, n) => "|\n" + indent(text.replace(/\s+$/, ""), n);

function envVar([name, value]) {
  if (typeof value === "string") return `- name: ${name}\n  value: ${q(value)}`;
  if (value.configMapKeyRef) {
    return `- name: ${name}\n  valueFrom:\n    configMapKeyRef:\n      name: devforge-ai-config\n      key: ${value.configMapKeyRef}`;
  }
  return `- name: ${name}\n  valueFrom:\n    secretKeyRef:\n      name: devforge-ai-secrets\n      key: ${value.secret}`;
}

const header = (name) =>
  `# GENERATED by infrastructure/kubernetes/generate.cjs - edit the generator, not this file.\n# ${name}\n`;

// ---------------------------------------------------------------- application services

function deployment(svc) {
  const env = [
    ["SPRING_PROFILES_ACTIVE", { configMapKeyRef: "SPRING_PROFILES_ACTIVE" }],
    ["DEVFORGE_JWT_ISSUER", { configMapKeyRef: "DEVFORGE_JWT_ISSUER" }],
    ["DEVFORGE_JWT_SIGNING_KEY", { secret: "jwt-signing-key" }],
    ["DEVFORGE_METRICS_TOKEN", { secret: "metrics-token" }],
    ["PROJECT_SERVICE_URL", "http://project-service:9002"],
    ["GIT_SERVICE_URL", "http://git-service:9005"],
  ];
  if (svc.db) {
    env.push(
      ["DEVFORGE_DB_URL", `jdbc:postgresql://postgres:5432/${svc.db}`],
      ["POSTGRES_USER", { secret: "postgres-username" }],
      ["POSTGRES_PASSWORD", { secret: "postgres-password" }]);
  }
  if (svc.kafka) {
    env.push(
      ["KAFKA_BOOTSTRAP_SERVERS", "kafka:29092"],
      ["DEVFORGE_KAFKA_REQUIRE_AUTHENTICATION", "true"],
      ["DEVFORGE_KAFKA_SECURITY_PROTOCOL", { configMapKeyRef: "DEVFORGE_KAFKA_SECURITY_PROTOCOL" }],
      ["DEVFORGE_KAFKA_SASL_MECHANISM", { configMapKeyRef: "DEVFORGE_KAFKA_SASL_MECHANISM" }],
      ["DEVFORGE_KAFKA_SASL_USERNAME", svc.name],
      ["DEVFORGE_KAFKA_SASL_PASSWORD", { secret: `kafka-password-${svc.name}` }]);
  }
  for (const e of svc.env ?? []) env.push(e);

  const volumeMounts = svc.volume
    ? `\n          volumeMounts:\n            - name: data\n              mountPath: ${svc.volume}`
    : "";
  const volumes = svc.volume
    ? `\n      volumes:\n        - name: data\n          persistentVolumeClaim:\n            claimName: ${svc.name}-data`
    : "";
  const pvc = svc.volume
    ? `---\napiVersion: v1\nkind: PersistentVolumeClaim\nmetadata:\n  name: ${svc.name}-data\n  namespace: ${NS}\nspec:\n  accessModes: [ReadWriteOnce]\n  resources:\n    requests:\n      storage: 2Gi\n`
    : "";

  return `---
apiVersion: v1
kind: Service
metadata:
  name: ${svc.name}
  namespace: ${NS}
spec:
  selector:
    app: ${svc.name}
  ports:
    - port: ${svc.port}
      targetPort: ${svc.port}
${pvc}---
apiVersion: apps/v1
kind: Deployment
metadata:
  name: ${svc.name}
  namespace: ${NS}
spec:
  replicas: 1
  selector:
    matchLabels:
      app: ${svc.name}
  template:
    metadata:
      labels:
        app: ${svc.name}
    spec:
      containers:
        - name: ${svc.name}
          image: devforge-ai/${svc.name}:latest
          # Built and loaded into the cluster rather than pulled; a registry deployment would
          # set a real tag and Always.
          imagePullPolicy: IfNotPresent
          ports:
            - containerPort: ${svc.port}
          env:
${indent(env.map(envVar).join("\n"), 12)}
          # Startup is slow (JVM, Flyway); readiness gates traffic, liveness restarts a stuck pod.
          startupProbe:
            httpGet: { path: /actuator/health, port: ${svc.port} }
            periodSeconds: 5
            failureThreshold: 60
          readinessProbe:
            httpGet: { path: /actuator/health, port: ${svc.port} }
            periodSeconds: 10
          livenessProbe:
            httpGet: { path: /actuator/health, port: ${svc.port} }
            periodSeconds: 20
            failureThreshold: 3
          resources:
            requests: { cpu: 50m, memory: 384Mi }
            limits: { memory: 768Mi }
          securityContext:
            runAsNonRoot: true
            allowPrivilegeEscalation: false
            capabilities: { drop: [ALL] }${volumeMounts}${volumes}
`;
}

function gateway() {
  const env = [
    ["SPRING_PROFILES_ACTIVE", { configMapKeyRef: "SPRING_PROFILES_ACTIVE" }],
    ["DEVFORGE_METRICS_TOKEN", { secret: "metrics-token" }],
    ["DEVFORGE_CORS_ORIGINS", { configMapKeyRef: "DEVFORGE_APP_BASE_URL" }],
    ["DEVFORGE_RATE_LIMIT_AUTH_PER_MINUTE", { configMapKeyRef: "DEVFORGE_RATE_LIMIT_AUTH_PER_MINUTE" }],
    ...Object.entries(GATEWAY_ROUTES).map(([k, v]) => [k, `http://${v}`]),
  ];
  return deployment({ name: "api-gateway", port: 8080 })
    .replace(/          env:\n[\s\S]*?\n          # Startup/, `          env:\n${indent(env.map(envVar).join("\n"), 12)}\n          # Startup`);
}

