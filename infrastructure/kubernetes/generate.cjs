// ---------------------------------------------------------------- infrastructure

function kafkaJaas() {
  // Built from the secret at start: Kubernetes expands $(VAR) references to earlier env vars.
  const users = ["user_admin=\"$(KAFKA_ADMIN_PASSWORD)\""].concat(
    SERVICES.filter((s) => s.kafka).map((s) => `user_${s.name}="$(KAFKA_PASSWORD_${s.name.replace(/-/g, "_").toUpperCase()})"`));
  return `org.apache.kafka.common.security.plain.PlainLoginModule required username="admin" password="$(KAFKA_ADMIN_PASSWORD)" ${users.join(" ")};`;
}

